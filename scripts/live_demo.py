"""Live example run of scripts/scenarios/*.yaml on real Gemini (+ BigQuery if
DATA_BACKEND=bigquery).

Each scenario file is one story: one user, one conversation, several turns.
Writes docs/live-demo.md. Usage: uv run python scripts/live_demo.py
Uses its own reports/preferences/trace files under data/demo/, so your own data is
untouched.
"""

import json
import shutil
import textwrap
import time
from pathlib import Path

import yaml

from retail_agent.agent import UserCtx, build_agent
from retail_agent.cli import make_embeddings, make_model, run_turn
from retail_agent.config import ROOT, load_settings
from retail_agent.db import make_db
from retail_agent.reports import ReportStore

SCENARIOS = Path(__file__).with_name("scenarios")
OUT = ROOT / "docs" / "live-demo.md"
WORK = ROOT / "data" / "demo"

NOTE = (
    "Answers are the model's verbatim output. The wording around the figures is the "
    "model's own reading and can be wrong, which is what the offline answer-quality "
    "eval in docs/technical-design.md (R6) is for. A stronger model "
    "(`LLM_MODEL=google_genai:gemini-3.8-flash`) reasons better at a higher cost and "
    "a smaller free quota."
)


def turn_lines(n: int, turn: dict, user: str, answer: str, rec: dict) -> list[str]:
    lines = [f"### {n}. {turn['shows']}", "", f"**{user}:** {turn['say']}", ""]
    for query in rec["queries"]:
        note = ["Rejected by the SQL guard:"] if query.get("rejected") else []
        lines += [*note, "```sql", query["sql"].strip(), "```", ""]
    other = [c["name"] for c in rec["tool_calls"] if c["name"] != "run_sql"]
    if other:
        lines += [f"Other tools called: {', '.join(f'`{n}`' for n in other)}", ""]
    if "confirm" in turn:
        said = "yes" if turn["confirm"] is True else "no"
        lines += [f"The user answered **{said}** to the confirmation prompt.", ""]
    scanned = sum(q.get("bytes_processed") or 0 for q in rec["queries"])
    lines += [
        (
            f"Trace: {rec['model_calls']} model calls "
            f"({', '.join(rec['models']) or 'n/a'}),"
            f" {rec['input_tokens']:,} input / {rec['output_tokens']:,} output tokens, "
            f"{len(rec['queries'])} SQL attempts ({rec['sql_errors']} failed, "
            f"{scanned / 1e6:.1f} MB scanned), "
            f"{rec['latency_ms'] / 1000:.1f} s, error: {rec['error']}"
        ),
        "",
        "**Answer:**",
        "",
        textwrap.indent(answer.replace("\r", "").strip(), "> ", lambda _: True),
        "",
    ]
    return lines


def main() -> None:
    settings = load_settings()
    users = yaml.safe_load((settings.config_dir / "users.yaml").read_text("utf-8"))
    shutil.rmtree(WORK, ignore_errors=True)
    WORK.mkdir(parents=True)
    trace, prefs = WORK / "traces.jsonl", WORK / "prefs.json"
    db, store = make_db(settings), ReportStore(WORK / "app.sqlite")

    lines = [
        "# Live example run",
        "",
        (
            f"Generated by `scripts/live_demo.py` from `scripts/scenarios/*.yaml` on "
            f"{time.strftime('%Y-%m-%d')}. Model `{settings.llm_model}` (fallback "
            f"`{settings.llm_fallback_model}`), data backend "
            f"`{settings.data_backend}`. "
            "Each story is one conversation; each turn shows every SQL attempt (as run "
            "after the guard, or as rejected by it), numbers "
            "from the turn's trace record "
            "and the final answer."
        ),
        "",
        NOTE,
        "",
    ]
    for path in sorted(SCENARIOS.glob("*.yaml")):
        story = yaml.safe_load(path.read_text(encoding="utf-8"))
        primary = story.get("primary_model")
        # A replaced primary (e.g. a model that does not exist) keeps the normal model
        # as its fallback.
        agent = build_agent(
            make_model(primary or settings.llm_model),
            db,
            store,
            prefs,
            fallback=make_model(
                settings.llm_model if primary else settings.llm_fallback_model
            ),
            embeddings=make_embeddings(settings.embed_model),
        )
        profile = users[story["user"]]
        brands = None if profile["role"] == "admin" else profile.get("brands", [])
        ctx = UserCtx(story["user"], profile["role"], brands, f"demo-{path.stem}")
        lines += [f"## {story['title']}", "", story["description"], ""]
        if primary:
            lines += [
                (
                    f"Primary model replaced by `{primary}`; `{settings.llm_model}` is "
                    "the fallback."
                ),
                "",
            ]
        for n, turn in enumerate(story["turns"], 1):
            approve = turn.get("confirm") is True  # YAML reads yes/no as booleans
            answer = run_turn(agent, ctx, turn["say"], lambda r, a=approve: a, trace)
            rec = json.loads(trace.read_text(encoding="utf-8").splitlines()[-1])
            lines += turn_lines(n, turn, story["user"], answer, rec)
            print(f"done: {story['title']} / {turn['shows']}")
    saved = prefs.read_text(encoding="utf-8") if prefs.exists() else "{}"
    lines += ["## Saved preferences after the run", "", "```json", saved.strip(), "```"]
    # Answers can end lines with spaces; the pre-commit whitespace hook rejects them.
    text = "\n".join(line.rstrip() for line in "\n".join(lines).splitlines())
    OUT.write_text(text + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
